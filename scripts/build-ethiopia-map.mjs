import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');

const geoPath = path.join(__dirname, 'eth-adm1.geojson');
const outPath = path.join(ROOT, 'data', 'ethiopia-map.js');

const geo = JSON.parse(readFileSync(geoPath, 'utf8'));

function perpDist([x, y], [ax, ay], [bx, by]) {
  const dx = bx - ax;
  const dy = by - ay;
  const len2 = dx * dx + dy * dy;
  if (len2 === 0) return Math.hypot(x - ax, y - ay);
  const t = Math.max(0, Math.min(1, ((x - ax) * dx + (y - ay) * dy) / len2));
  return Math.hypot(x - (ax + t * dx), y - (ay + t * dy));
}

function simplify(points, tol) {
  if (points.length <= 4) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [first, last] = stack.pop();
    let maxDist = 0;
    let idx = -1;
    for (let i = first + 1; i < last; i++) {
      const d = perpDist(points[i], points[first], points[last]);
      if (d > maxDist) { maxDist = d; idx = i; }
    }
    if (maxDist > tol && idx !== -1) {
      keep[idx] = 1;
      stack.push([first, idx], [idx, last]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

let lonMin = Infinity, lonMax = -Infinity, latMin = Infinity, latMax = -Infinity;
for (const f of geo.features) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys)
    for (const ring of poly)
      for (const [lon, lat] of ring) {
        if (lon < lonMin) lonMin = lon;
        if (lon > lonMax) lonMax = lon;
        if (lat < latMin) latMin = lat;
        if (lat > latMax) latMax = lat;
      }
}

const midLat = (latMin + latMax) / 2;
const KX = Math.cos((midLat * Math.PI) / 180);
const TOL = 0.012;

function project(lon, lat) {
  return [(lon - lonMin) * KX, latMax - lat];
}

const regions = [];
for (const f of geo.features) {
  const name = f.properties.shapeName || f.properties.NAME_1 || f.properties.name || 'Region';
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const d = polys
    .map((poly) => simplify(poly[0], TOL))
    .filter((ring) => ring.length >= 4)
    .map((ring) => {
      let last = null;
      const pts = [];
      for (const [lon, lat] of ring) {
        const [x, y] = project(lon, lat);
        const px = x.toFixed(2);
        const py = y.toFixed(2);
        if (px === last && py === last) continue;
        pts.push(px + ' ' + py);
        last = [px, py];
      }
      return 'M' + pts.join('L') + 'Z';
    })
    .join(' ');
  if (d) regions.push({ name, d });
}

const W = ((lonMax - lonMin) * KX).toFixed(2);
const H = (latMax - latMin).toFixed(2);
const VB = [0, 0, +W, +H];

const svgPaths = regions.map((r, i) => {
  const safeName = r.name.replace(/"/g, '&quot;');
  return '  <path id="region-' + i + '" class="region-path" data-name="' + safeName + '" d="' + r.d + '" />';
}).join('\n');
const svgString =
  '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' +
  W + ' ' + H +
  '" preserveAspectRatio="xMidYMid meet" role="img" aria-label="Map of Ethiopia" class="eth-map-svg">\n' +
  '  <title>Map of Ethiopia</title>\n' +
  '  <desc>Regional boundaries of Ethiopia used by Mule Ethiopia Tour.</desc>\n' +
  svgPaths + '\n</svg>';

const out = '/**\n' +
  ' * Auto-generated by scripts/build-ethiopia-map.mjs - do not edit by hand.\n' +
  ' * Source: geoBoundaries gbOpen ETH ADM1 (open licence).\n' +
  ' *\n' +
  ' * SVG paths are in projected map units; the viewBox is [0, 0, W, H].\n' +
  ' * projectLatLon() maps real coordinates onto the same space.\n' +
  ' * Region names are verbatim GeoJSON labels (shapeName / NAME_1).\n' +
  ' */\n\n' +
  '// ---- projection constants ----\n' +
  'const LON_MIN = ' + lonMin.toFixed(4) + ';\n' +
  'const LAT_MIN = ' + latMin.toFixed(4) + ';\n' +
  'const LAT_MAX = ' + latMax.toFixed(4) + ';\n' +
  'const KX = ' + KX.toFixed(6) + ';\n\n' +
  '/**\n' +
  ' * lat/lon -> [x, y] in map units (y grows downward, like SVG).\n' +
  ' * Destinations call this to place their pins on the map.\n' +
  ' */\n' +
  'export function projectLatLon(lat, lon) {\n' +
  '  return [(lon - LON_MIN) * KX, LAT_MAX - lat];\n' +
  '}\n\n' +
  '/**\n' +
  ' * ViewBox used by the interactive SVG on the homepage.\n' +
  ' */\n' +
  'export const ETHIOPIA_VIEWBOX = ' + JSON.stringify(VB) + ';\n\n' +
  '/**\n' +
  ' * All Ethiopian regions (ADM1) with their SVG path data.\n' +
  ' * Names are the raw GeoJSON labels (shapeName / NAME_1).\n' +
  ' */\n' +
  'export const ETHIOPIA_REGIONS = ' + JSON.stringify(regions, null, 2) + ';\n\n' +
  '/**\n' +
  ' * Optional SSR preview SVG + CSS. Not used by the React map itself.\n' +
  ' */\n' +
  'export const ETHIOPIA_MAP_PREVIEW = ' + JSON.stringify(svgString) + ';\n\n' +
  'export const ETHIOPIA_MAP_CSS = `.eth-map-svg { width: 100%; height: auto; display: block; }\n' +
  '.region-path { fill: #27403a; stroke: #e3b65b; stroke-width: 0.5; transition: fill 0.2s ease; }\n' +
  '.region-path:hover { fill: #3a5d52; }`;\n\n' +
  'console.log("data/ethiopia-map.js written - " + regions.length + " regions, viewBox " + W + "x" + H + ", " + (out.length / 1024).toFixed(1) + " KB");\n';

writeFileSync(outPath, out, 'utf8');
console.log('Wrote ' + outPath + ' - ' + regions.length + ' regions, viewBox ' + W + 'x' + H + ', ' + (out.length / 1024).toFixed(1) + ' KB');
